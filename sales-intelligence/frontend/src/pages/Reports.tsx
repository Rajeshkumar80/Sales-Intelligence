import { useState } from 'react'
import { Download, FileSpreadsheet } from 'lucide-react'
import { downloadCsv, qs } from '../api/client'
import { SectionHeader } from '../components/ui'

const datasets = [
  { key: 'transactions', title: 'Transaction history', hint: 'Raw rows with processing state, source and batch ID.' },
  { key: 'products', title: 'Product totals', hint: 'Revenue, quantity and order count per product from the fact cube.' },
  { key: 'daily', title: 'Daily sales', hint: 'Revenue and units per sale date.' },
  { key: 'monthly', title: 'Monthly sales', hint: 'Revenue and units per calendar month.' },
  { key: 'regional', title: 'Regional sales', hint: 'Revenue, quantity and orders per region.' },
  { key: 'category', title: 'Category sales', hint: 'Revenue and quantity per category.' },
  { key: 'hive', title: 'Hive snapshot', hint: 'Every Hive aggregate section for the latest batch.' },
]

export default function Reports() {
  const [dateFrom, setDateFrom] = useState('')
  const [dateTo, setDateTo] = useState('')
  const query = qs({ date_from: dateFrom, date_to: dateTo })

  return (
    <div className="space-y-6">
      <SectionHeader
        title="Reports"
        subtitle="CSV exports are generated by the backend from the same aggregates the dashboard shows. Cells starting with =, +, - or @ are neutralised."
      />

      <div className="card grid gap-3 sm:grid-cols-2 lg:max-w-xl">
        <div>
          <label className="label" htmlFor="from">From date (optional)</label>
          <input id="from" type="date" className="input" value={dateFrom} onChange={(e) => setDateFrom(e.target.value)} />
        </div>
        <div>
          <label className="label" htmlFor="to">To date (optional)</label>
          <input id="to" type="date" className="input" value={dateTo} onChange={(e) => setDateTo(e.target.value)} />
        </div>
        <p className="text-xs text-slate-500 dark:text-slate-400 sm:col-span-2">
          Date filters apply to fact-cube sections (products, daily, monthly, regional, category). Transaction exports use ISO-8601 timestamps stored in UTC.
        </p>
      </div>

      <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
        {datasets.map((dataset) => (
          <div key={dataset.key} className="card flex flex-col justify-between gap-3">
            <div className="flex items-start gap-3">
              <span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-brand-50 text-brand-600 dark:bg-brand-500/10 dark:text-brand-300">
                <FileSpreadsheet className="h-4 w-4" />
              </span>
              <div>
                <h3 className="text-sm font-semibold">{dataset.title}</h3>
                <p className="mt-1 text-xs leading-relaxed text-slate-500 dark:text-slate-400">{dataset.hint}</p>
              </div>
            </div>
            <button
              type="button"
              className="btn-secondary self-start"
              onClick={() => downloadCsv(`/api/sales/reports/export/${dataset.key}.csv${query}`, `sales-${dataset.key}.csv`)}
            >
              <Download className="h-4 w-4" /> Download CSV
            </button>
          </div>
        ))}
      </div>
    </div>
  )
}
